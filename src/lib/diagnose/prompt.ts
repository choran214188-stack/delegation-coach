export function buildUserMessage(input: DiagnoseInput): string {
  const name = input.memberName?.trim() || "이 팀장";
  return `[위임하려는 업무]
${input.task.trim()}

[대상 팀장: ${name}]
${input.memberContext.trim()}

위 팀장이 이 업무에 대해 어느 발달수준에 있는지 진단하고, 어떤 리더십으로 어떻게 위임을 설계·실행해야 하는지 JSON 으로만 답하세요.`;
}
